import { useEffect } from "react";
import { fetchAuthMe as apiFetchAuthMe } from "./api";

export const useAppLifecycleSessionValidationEffects = ({
  authToken,
  fetchAuthMe = apiFetchAuthMe,
  invalidateSession,
  setSession,
}) => {
  useEffect(() => {
    if (!authToken) return undefined;

    let mounted = true;
    const validateSession = async () => {
      try {
        const result = await fetchAuthMe();
        if (!mounted) return;
        setSession(prev => prev ? {
          ...prev,
          user: result.user || prev.user,
          expiresAt: result.expiresAt || prev.expiresAt || null,
        } : prev);
      } catch (error) {
        if (!mounted) return;
        if (error?.status === 401 || error?.status === 403) {
          invalidateSession();
        }
      }
    };

    const timer = window.setInterval(validateSession, 30000);
    return () => {
      mounted = false;
      window.clearInterval(timer);
    };
  }, [authToken]);
};
