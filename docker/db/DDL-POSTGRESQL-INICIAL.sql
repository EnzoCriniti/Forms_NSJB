CREATE TABLE event_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  type TEXT NOT NULL,
  template_id BIGINT REFERENCES message_templates(id) ON DELETE SET NULL,
  body TEXT NOT NULL,
  config_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  scheduled_for TIMESTAMPTZ,
  window_option TEXT,
  auto_dispatch_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  status TEXT NOT NULL DEFAULT 'rascunho',
  sent_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_event_messages_event_id ON event_messages(event_id);
CREATE INDEX idx_event_messages_status_scheduled ON event_messages(status, scheduled_for);

CREATE TABLE message_dispatch_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
