  mode TEXT NOT NULL,
  rendered_body TEXT NOT NULL,
  recipients_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  group_name TEXT,
  status TEXT NOT NULL DEFAULT 'logged_only',
